// Records real Gemini and Gemma readings of Try it's example sentences (demo/try.mjs EXAMPLES) into src/try/recorded.ts, so
// the demo serves them without a model call, as Valio replies are replayed. Reads the category and claim lists from the
// remote D1 (read-only), the model key from GEMINI_API_KEY; prints no key. Run with cf.env and gemini.env sourced:
//   pnpm exec tsx scripts/record-readings.ts
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { EXAMPLES } from '../demo/try.mjs';
import type { Env } from '../src/env';
import { readTwice, type Readings } from '../src/interpret/gemini';

/** The demo clock's day: "by Monday" and "for Friday" are read against Friday 13 Nov. */
const TODAY = '2026-11-13';
const GEMINI_MODEL = process.env.GEMINI_MODEL ?? 'gemini-3.8-flash';
const GEMMA_MODEL = process.env.GEMMA_MODEL ?? 'gemma-4-31b-it';

/** Rows of a read-only query against the remote D1 catalogue. */
function d1(sql: string): Record<string, unknown>[] {
  const out = execFileSync('pnpm', ['exec', 'wrangler', 'd1', 'execute', 'lazydoor', '--remote', '--json', '--command', sql], { encoding: 'utf8' });
  return JSON.parse(out.slice(out.indexOf('[')))[0].results;
}

const categories = d1('SELECT category, names FROM category_names ORDER BY category');
const claims = d1("SELECT DISTINCT value AS id FROM products, json_each(products.claims) WHERE products.claims IS NOT NULL ORDER BY 1");
const env = {
  GEMINI_API_KEY: process.env.GEMINI_API_KEY,
  GEMINI_MODEL,
  GEMMA_MODEL,
  DB: { prepare: (sql: string) => ({ all: async () => ({ results: sql.includes('category_names') ? categories : claims }) }) },
} as unknown as Env;

const recorded: Record<string, Readings> = {};
for (const [i, text] of (EXAMPLES as string[]).entries()) {
  if (i) await new Promise((r) => setTimeout(r, 20_000));
  let r = await readTwice(env, text, TODAY, fetch);
  if (!r.gemma) {
    await new Promise((res) => setTimeout(res, 60_000));
    r = await readTwice(env, text, TODAY, fetch);
  }
  if (!r.gemma) throw new Error(`Gemma gave no reading for "${text}"`);
  recorded[text] = r;
  console.log(`recorded: ${text}`);
}

writeFileSync(
  'src/try/recorded.ts',
  `// Generated by scripts/record-readings.ts on ${new Date().toISOString().slice(0, 10)}: real ${GEMINI_MODEL} and ${GEMMA_MODEL} readings of
// Try it's example sentences, read against ${TODAY} (the demo clock's day). Try it serves them for an exact text match instead
// of calling the models, and marks the draft cached; free text still goes to the models.
import type { Readings } from '../interpret/gemini';

/** The recorded readings by exact example sentence. */
export const RECORDED: Record<string, Readings> = ${JSON.stringify(recorded, null, 2)};
`,
);
console.log(`wrote src/try/recorded.ts (${Object.keys(recorded).length} sentences)`);
